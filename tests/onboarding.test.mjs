import test from 'node:test';
import assert from 'node:assert/strict';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { Window } from 'happy-dom';
import { createServer } from 'vite';
import { createDemo, emptyState } from '../server/demo.mjs';
import { analyze } from '../server/domain.mjs';

test('onboarding is read-only, highlights real areas, pauses, resumes and completes without polluting history', async t => {
  const window = new Window({ url: 'http://localhost:3000/#overview' });
  Object.defineProperty(window, 'innerWidth', { value: 1280, configurable: true });
  Object.defineProperty(window, 'innerHeight', { value: 900, configurable: true });
  const originals = new Map();
  const globals = { window, document: window.document, history: window.history, Event: window.Event, MutationObserver: window.MutationObserver, ResizeObserver: window.ResizeObserver, getComputedStyle: window.getComputedStyle.bind(window), requestAnimationFrame: window.requestAnimationFrame.bind(window), cancelAnimationFrame: window.cancelAnimationFrame.bind(window), IS_REACT_ACT_ENVIRONMENT: true, fetch: async () => { throw new Error('The onboarding must not issue requests'); } };
  for (const [key, value] of Object.entries(globals)) { originals.set(key, Object.getOwnPropertyDescriptor(globalThis, key)); Object.defineProperty(globalThis, key, { value, configurable: true, writable: true }); }
  const vite = await createServer({ server: { middlewareMode: true, hmr: { port: 24699 } }, optimizeDeps: { noDiscovery: true, entries: [] }, appType: 'custom' });
  const host = window.document.createElement('div'); host.id = 'root'; window.document.body.append(host);
  const root = createRoot(host);
  t.after(async () => { await act(async () => root.unmount()); await vite.close(); await window.happyDOM.close(); for (const [key, descriptor] of originals) { if (descriptor) Object.defineProperty(globalThis, key, descriptor); else delete globalThis[key]; } });
  window.HTMLElement.prototype.getBoundingClientRect = function () {
    const isCard = this.classList.contains('tour-card');
    const mobile = window.innerWidth < 760;
    const left = isCard ? 0 : mobile ? 20 : 240, top = isCard ? 0 : mobile ? 80 : 140, width = isCard ? Math.min(420, window.innerWidth - 24) : mobile ? window.innerWidth - 40 : 600, height = isCard ? mobile ? 496 : 500 : 180;
    return { left, top, width, height, right: left + width, bottom: top + height, x: left, y: top, toJSON() {} };
  };
  const nav = await vite.ssrLoadModule('/src/page-navigation.tsx');
  const { default: Onboarding } = await vite.ssrLoadModule('/src/Onboarding.tsx');
  const content = await vite.ssrLoadModule('/src/onboarding-steps.ts');
  const state = createDemo();
  const data = { ...analyze(state, 30), suppliers: state.suppliers, orders: [], warehouseTickets: [], settings: state.settings, connection: { dataReady: true }, emailRouting: { configured: false, debugRecipient: 'debug@example.test' } };
  const before = JSON.stringify(data);
  const steps = content.onboardingSteps(data, content.tourExamples(data));
  assert.equal(steps.length, 20);
  assert.equal(new Set(steps.map(s => s.id)).size, 20);
  assert.equal(JSON.stringify(data), before);
  const empty = { ...emptyState(), products: [], connection: {}, emailRouting: {} };
  const emptySteps = content.onboardingSteps(empty, {});
  assert.equal(emptySteps.find(s => s.id === 'article').route, '#products');
  assert.equal(emptySteps.find(s => s.id === 'shortages').route, '#warehouse');
  assert.equal(content.readTourProgress({ getItem: () => '{broken' }), null);
  assert.equal(content.readTourProgress({ getItem: () => JSON.stringify({ index: 99, status: 'paused' }) }), null);
  assert.deepEqual(content.readTourProgress({ getItem: () => JSON.stringify({ index: 4, status: 'active' }) }), { index: 4, status: 'paused' });
  let starts = 0, ends = 0;
  function Fixture() {
    nav.usePageRoute();
    return React.createElement(React.Fragment, null, React.createElement('div', { className: 'app-shell' }, ...[...new Set(steps.flatMap(s => s.targets))].map(name => React.createElement('section', { key: name, 'data-tour': name }, name))), React.createElement(Onboarding, { data, onStart: () => starts++, onEnd: () => ends++ }));
  }
  const click = async selector => { const button = window.document.querySelector(selector); assert.ok(button, selector); await act(async () => button.click()); };
  const settle = () => act(async () => { await new Promise(resolve => setTimeout(resolve, 280)); });
  const count = history.length;
  await act(async () => root.render(React.createElement(Fixture)));
  assert.ok(window.document.querySelector('.tour-card'));
  assert.equal(host.inert, true);
  assert.equal(host.getAttribute('aria-hidden'), 'true');
  assert.match(window.document.querySelector('#tour-title').textContent, /Schritt/);
  await click('.tour-card-footer .button.primary');
  await settle();
  assert.ok(window.document.querySelector('.tour-spotlight'));
  assert.equal(window.document.querySelectorAll('.tour-dim').length, 4);
  assert.equal(window.document.querySelector('[role="progressbar"]').getAttribute('aria-valuenow'), '2');
  Object.defineProperty(window, 'innerWidth', { value: 390, configurable: true });
  Object.defineProperty(window, 'innerHeight', { value: 800, configurable: true });
  await act(async () => window.dispatchEvent(new window.Event('resize'))); await settle();
  const mobileCard = window.document.querySelector('.tour-card');
  const mobileSpot = window.document.querySelector('.tour-spotlight');
  assert.ok(Number.parseFloat(mobileCard.style.left) + mobileCard.getBoundingClientRect().width <= 390);
  assert.ok(Number.parseFloat(mobileSpot.style.top) + Number.parseFloat(mobileSpot.style.height) < Number.parseFloat(mobileCard.style.top));
  Object.defineProperty(window, 'innerWidth', { value: 1280, configurable: true });
  Object.defineProperty(window, 'innerHeight', { value: 900, configurable: true });
  await act(async () => window.dispatchEvent(new window.Event('resize')));
  const last = window.document.querySelector('.tour-card-footer>div:last-child>button');
  last.focus();
  await act(async () => window.document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true })));
  assert.equal(window.document.activeElement, window.document.querySelector('.tour-card button'));
  await act(async () => window.document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true })));
  assert.equal(host.inert, false);
  assert.equal(host.getAttribute('aria-hidden'), null);
  assert.equal(window.document.querySelector('.tour-card'), null);
  assert.equal(JSON.parse(window.localStorage.getItem(content.ONBOARDING_KEY)).status, 'paused');
  await click('.tour-launcher');
  assert.equal(window.document.querySelector('[role="progressbar"]').getAttribute('aria-valuenow'), '2');
  for (let index = 2; index <= 7; index++) await click('.tour-card-footer .button.primary');
  assert.match(window.location.hash, /^#products\/product\//);
  await click('.tour-progress>button');
  assert.equal(window.document.querySelectorAll('.tour-contents li').length, 20);
  await click('.tour-contents li:last-child button');
  assert.equal(window.location.hash, '#overview');
  await click('.tour-card-footer .button.primary');
  assert.equal(JSON.parse(window.localStorage.getItem(content.ONBOARDING_KEY)).status, 'completed');
  assert.equal(host.inert, false);
  assert.equal(history.length, count, 'The tour replaces routes rather than adding twenty history entries');
  assert.equal(starts, ends);
  await act(async () => root.render(React.createElement(Fixture, { key: 'reload' })));
  assert.equal(window.document.querySelector('.tour-card'), null, 'Completed onboarding does not automatically restart');
  await click('.tour-launcher');
  assert.equal(window.document.querySelector('[role="progressbar"]').getAttribute('aria-valuenow'), '1');
  await click('.tour-card-footer>div:last-child>button');
  assert.equal(JSON.parse(window.localStorage.getItem(content.ONBOARDING_KEY)).status, 'skipped');
  assert.equal(JSON.stringify(data), before);
});
